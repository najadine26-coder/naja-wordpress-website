<h3>Mandi and madfoon</h3>
<p>Mandi is known for tender meat and fragrant rice, traditionally cooked slowly in a pit or tandoor-style oven so the meat stays moist. Madfoon is a related dish whose name refers to the way it was traditionally cooked underground. Restaurants often use modern ovens, but the idea is the same: soft meat and rice that carries its aroma.</p>

<h3>Jareesh, harees and saleeg</h3>
