<h2>The foundations of Saudi cooking</h2>
<p>Traditional Saudi food is built on rice, wheat, meat, dairy and dates, flavoured with warm spices rather than heat. Cardamom, cloves, cinnamon, saffron and dried lime appear again and again. Because Saudi Arabia is a big country, dishes differ from region to region: Najdi cooking in the centre, Hijazi dishes in the west, and Gulf coastal flavours in the east.</p>

